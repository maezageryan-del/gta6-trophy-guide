const dataPath = new URL('../app/data/trophies.json', import.meta.url);
const data = JSON.parse(readFileSync(dataPath, 'utf8'));
let total = 0;
for (const trophy of data.trophies) {
  const list = EXPANDED[trophy.id];
  if (!list || list.length < 7) throw new Error(`trophy ${trophy.id}: expanded list missing or too short`);
  const cites = trophy.cites && trophy.cites.length ? trophy.cites : ['exophase'];
  trophy.steps = list.map((t, i) => ({ t, c: cites[i % cites.length] }));
  total += trophy.steps.length;
}
writeFileSync(dataPath, JSON.stringify(data, null, 2) + '\n');
const missables = data.trophies.filter((t) => t.missable).length;
console.log(`trophies=${data.trophies.length} steps=${total} citations=${total} missables=${missables}`);
